import { useEffect, useRef, useState } from "react";
import { gsap } from "gsap";
import { Pencil, Copy, Trash2, Share2, Plus } from "lucide-react";
import ManifestTable, { ManifestSkeleton } from "../components/ManifestTable";
import ContainerInfoOverlay from "../components/ContainerInfoOverlay";
import ExportMenu from "../components/ExportMenu";
import CreateVoyageModal from "../components/CreateVoyageModal";
import ConfirmDialog from "../components/ConfirmDialog";
import { useToast } from "../components/Toast";
import {
  TOKENS,
  voyageStats,
  VOYAGE_STATUS_COLORS,
  VOYAGE_STATUS_CYCLE,
} from "../data/statusHelpers";

const iconBtn = {
  background: "none",
  border: `1px solid ${TOKENS.border}`,
  color: TOKENS.steel,
  borderRadius: 4,
  padding: "7px 9px",
  cursor: "pointer",
  display: "flex",
  alignItems: "center",
  gap: 6,
  fontFamily: TOKENS.mono,
  fontSize: 11,
};

function buildShareText(voyage) {
  const s = voyageStats(voyage);
  const lines = (voyage.containers || [])
    .map((c, i) => {
      const bags = (c.lines || []).reduce((a, l) => a + Number(l.qty || 0), 0);
      const cargo = [...new Set((c.lines || []).map((l) => l.cargo))].join(", ") || "empty";
      return `${i + 1}. ${c.number || "—"} — ${cargo} (${bags} bags) — ${
        c.sealed ? "SEALED" : "open"
      }`;
    })
    .join("\n");
  return `*VOYAGE SUMMARY — ${voyage.voyageNo}*
Vessel: ${voyage.vessel}
Date: ${voyage.date}
Route: ${voyage.pol} → ${voyage.pod}

*Containers: ${s.total}* (${s.sealed} sealed)
*Total Cargo: ${s.bags} bags / ${s.mt.toFixed(1)} MT*

Container-wise:
${lines}

_Generated by Kraft Stuffing Log_`;
}

export default function VoyageDetailView({ app, voyageId }) {
  const { state, navigate, setActiveVoyage, updateVoyageEntry, archiveVoyageEntry, duplicateVoyage, addContainerEntry, exportXlsx, exportPdf, profilesById } = app;
  const { showToast } = useToast();
  const [selectedContainerId, setSelectedContainerId] = useState(null);
  const [editing, setEditing] = useState(false);
  const [confirmingDelete, setConfirmingDelete] = useState(false);
  const [online, setOnline] = useState(typeof navigator !== "undefined" ? navigator.onLine : true);
  const barRef = useRef(null);

  const voyage = state.voyages.find((v) => v.id === voyageId);

  useEffect(() => {
    if (voyageId) setActiveVoyage(voyageId);
  }, [voyageId, setActiveVoyage]);

  useEffect(() => {
    const on = () => setOnline(true);
    const off = () => setOnline(false);
    window.addEventListener("online", on);
    window.addEventListener("offline", off);
    return () => {
      window.removeEventListener("online", on);
      window.removeEventListener("offline", off);
    };
  }, []);

  const s = voyage ? voyageStats(voyage) : { sealed: 0, total: 0, mt: 0, bags: 0 };
  const pct = s.total > 0 ? Math.round((s.sealed / s.total) * 100) : 0;

  useEffect(() => {
    if (barRef.current) {
      gsap.fromTo(barRef.current, { width: "0%" }, { width: `${pct}%`, duration: 0.6, ease: "power2.out" });
    }
  }, [pct, voyageId]);

  if (state.loading && !voyage) {
    return <ManifestSkeleton />;
  }
  if (!voyage) {
    return (
      <div style={{ padding: 40, fontFamily: TOKENS.mono, color: TOKENS.steel }}>
        Voyage not found.{" "}
        <button onClick={() => navigate("voyages")} style={{ color: TOKENS.amber, background: "none", border: "none", cursor: "pointer" }}>
          ← Back to voyages
        </button>
      </div>
    );
  }

  const cycleStatus = () => {
    const idx = VOYAGE_STATUS_CYCLE.indexOf(voyage.status);
    const next = VOYAGE_STATUS_CYCLE[(idx + 1) % VOYAGE_STATUS_CYCLE.length];
    updateVoyageEntry(voyage.id, { status: next, archived: next === "ARCHIVED" });
    showToast(`Status → ${next}`, "info");
  };

  const onShare = async () => {
    const text = buildShareText(voyage);
    try {
      await navigator.clipboard.writeText(text);
      showToast("Copied to clipboard ✓", "success");
    } catch {
      showToast("Copy failed", "error");
    }
  };

  const onDuplicate = () => {
    const v = duplicateVoyage(voyage.id);
    if (v) {
      showToast(`Duplicated from ${voyage.voyageNo}`, "success");
      navigate("voyage-detail", { voyageId: v.id });
    }
  };

  const statusColor = VOYAGE_STATUS_COLORS[voyage.status] || TOKENS.steel;
  const canDelete = voyage.status === "DRAFT" || voyage.status === "ARCHIVED";

  return (
    <div style={{ maxWidth: 1200, margin: "0 auto", padding: "14px 18px 40px" }}>
      {/* Breadcrumb */}
      <div style={{ fontFamily: TOKENS.mono, fontSize: 11, color: TOKENS.steel, marginBottom: 10 }}>
        <button
          onClick={() => navigate("voyages")}
          style={{ background: "none", border: "none", color: TOKENS.steel, cursor: "pointer", fontFamily: TOKENS.mono, fontSize: 11, padding: 0 }}
        >
          Voyages
        </button>{" "}
        / <span style={{ color: "#cbd5e1" }}>{voyage.voyageNo}</span>
        <span style={{ marginLeft: 10, color: online ? TOKENS.green : TOKENS.steel }}>
          {online ? "● LIVE" : "○ SYNCING"}
        </span>
      </div>

      {/* Title row */}
      <div style={{ display: "flex", justifyContent: "space-between", alignItems: "flex-start", flexWrap: "wrap", gap: 12 }}>
        <div>
          <div style={{ fontFamily: TOKENS.condensed, fontWeight: 800, fontSize: 30, color: "#e8eef4", lineHeight: 1 }}>
            {voyage.vessel}
          </div>
          <div style={{ fontFamily: TOKENS.mono, fontSize: 12, color: TOKENS.steel, marginTop: 4 }}>
            {voyage.voyageNo} · {voyage.pol} → {voyage.pod} · {voyage.date}
          </div>
        </div>
        <div style={{ display: "flex", gap: 8, flexWrap: "wrap", alignItems: "center" }}>
          <button onClick={cycleStatus} style={{ ...iconBtn, color: statusColor, borderColor: statusColor }}>
            {voyage.status}
          </button>
          <button onClick={() => setEditing(true)} style={iconBtn}><Pencil size={14} /></button>
          <button onClick={onDuplicate} style={iconBtn}><Copy size={14} /></button>
          <button onClick={onShare} style={iconBtn}><Share2 size={14} /> Share</button>
          <ExportMenu onExportXlsx={() => exportXlsx(voyage)} onExportPdf={() => exportPdf(voyage)} />
          {canDelete && (
            <button onClick={() => setConfirmingDelete(true)} style={{ ...iconBtn, color: TOKENS.red, borderColor: "#3a0808" }}>
              <Trash2 size={14} />
            </button>
          )}
        </div>
      </div>

      {confirmingDelete && (
        <ConfirmDialog
          message={`Delete ${voyage.voyageNo}? This cannot be undone.`}
          confirmLabel="DELETE"
          onCancel={() => setConfirmingDelete(false)}
          onConfirm={() => {
            archiveVoyageEntry(voyage.id);
            setConfirmingDelete(false);
            showToast(`${voyage.voyageNo} archived`, "success");
            navigate("voyages");
          }}
        />
      )}

      {/* Status / progress bar */}
      <div style={{ marginTop: 16, background: TOKENS.surface, border: `1px solid ${TOKENS.border}`, borderRadius: 10, padding: "12px 16px" }}>
        <div style={{ display: "flex", justifyContent: "space-between", fontFamily: TOKENS.mono, fontSize: 11, color: TOKENS.steel }}>
          <span>{s.sealed} of {s.total} containers sealed</span>
          <span style={{ color: TOKENS.amber }}>{pct}%</span>
        </div>
        <div style={{ height: 8, background: TOKENS.bg, borderRadius: 4, marginTop: 8, overflow: "hidden" }}>
          <div ref={barRef} style={{ height: "100%", width: `${pct}%`, background: TOKENS.amber, borderRadius: 4 }} />
        </div>
      </div>

      {/* Manifest */}
      <div style={{ marginTop: 16 }}>
        {voyage.containers.length === 0 ? (
          <div style={{ textAlign: "center", padding: "50px 20px" }}>
            <div style={{ fontFamily: TOKENS.condensed, fontWeight: 800, fontSize: 24, color: "#1c2d42" }}>
              NO CONTAINERS — tap + to add one
            </div>
            <button
              onClick={() => addContainerEntry(voyage.id)}
              style={{ marginTop: 16, ...iconBtn, color: TOKENS.amber, borderColor: TOKENS.amber }}
            >
              <Plus size={14} /> Add container
            </button>
          </div>
        ) : (
          <>
            <div style={{ display: "flex", justifyContent: "flex-end", marginBottom: 8 }}>
              <button
                onClick={() => addContainerEntry(voyage.id)}
                style={{ ...iconBtn, color: TOKENS.amber, borderColor: TOKENS.amber }}
              >
                <Plus size={14} /> Add container
              </button>
            </div>
            <ManifestTable
              containers={voyage.containers}
              voyageNo={voyage.voyageNo}
              selectedContainerId={selectedContainerId}
              onSelectContainer={setSelectedContainerId}
              onOpenLog={(cid) => navigate("container-log", { containerId: cid })}
            />
          </>
        )}
      </div>

      {selectedContainerId && (() => {
        const c = voyage.containers.find((x) => x.id === selectedContainerId);
        return c ? (
          <ContainerInfoOverlay
            container={c}
            onClose={() => setSelectedContainerId(null)}
            onSelectLine={() => navigate("container-log", { containerId: c.id })}
            profilesById={profilesById}
          />
        ) : null;
      })()}

      {editing && (
        <CreateVoyageModal
          voyage={voyage}
          onClose={() => setEditing(false)}
          onSubmit={(patch) => {
            updateVoyageEntry(voyage.id, patch);
            setEditing(false);
            showToast("Voyage updated", "success");
          }}
        />
      )}
    </div>
  );
}
